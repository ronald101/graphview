/** The longest term, in words. */
const MAX_WORDS = 6;

export interface TermList {
  full: ReadonlySet<string>;
  first: ReadonlySet<string>;
  maxWords: number;
}

export const PRIVATE_TERMS: TermList = { full: FULL, first: FIRST, maxWords: MAX_WORDS };

const sha = (s: string) => createHash('sha256').update(s).digest('hex');

/** Words as the terms were cut: runs of letters, digits and underscores, in lower case. */
export const words = (text: string): string[] => text.toLowerCase().match(/[a-z0-9_]+/g) ?? [];

/** Hashes a list of terms, for tests of the scan itself. */
export function termList(terms: string[]): TermList {
  const cut = terms.map((t) => words(t).join(' '));
  return {
    full: new Set(cut.map(sha)),
    first: new Set(cut.map((t) => sha(t.split(' ')[0]))),
    maxWords: Math.max(...cut.map((t) => t.split(' ').length)),
  };
}

/** The phrases of a text that are on the list. */
export function leaks(text: string, list: TermList = PRIVATE_TERMS): string[] {
  const w = words(text);
  const found = new Set<string>();
  for (let i = 0; i < w.length; i++) {
    if (!list.first.has(sha(w[i]))) continue;
    let phrase = '';
    for (let n = 0; n < list.maxWords && i + n < w.length; n++) {
      phrase = n ? `${phrase} ${w[i + n]}` : w[i];
      if (list.full.has(sha(phrase))) found.add(phrase);
    }
  }
  return [...found];
}
