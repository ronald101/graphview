const share = <K extends string>(c: Common<number, K>) => new SliderSetting({ ...c, min: 0, max: 1, step: 0.01 });
const MOUSE = [
  ['pan', 'Pan'],
  ['rotate', 'Turn'],
  ['dolly', 'Zoom'],
  ['none', 'Nothing'],
] as const;
const ONE_FINGER = [
  ['pan', 'Pan'],
  ['rotate', 'Turn'],
  ['none', 'Nothing'],
] as const;
const TWO_FINGERS = [
  ['dolly-pan', 'Zoom and pan'],
  ['dolly-rotate', 'Zoom and turn'],
  ['none', 'Nothing'],
] as const;
const button = <K extends string>(key: K, label: string, d: 'pan' | 'rotate' | 'dolly' | 'none') =>
  new SelectSetting({
    key,
    group: 'Camera',
    label,
    description: `What ${label.toLowerCase()} does.`,
    default: d,
    options: MOUSE,
  });

/** The canvas's keyboard actions (6.14). */
export const KEY_ACTIONS = [
  ['fit', 'Fit'],
  ['pan-left', 'Pan left'],
  ['pan-right', 'Pan right'],
  ['pan-up', 'Pan up'],
  ['pan-down', 'Pan down'],
  ['zoom-in', 'Zoom in'],
  ['zoom-out', 'Zoom out'],
  ['turn-left', 'Turn left'],
  ['turn-right', 'Turn right'],
  ['clear', 'Clear the path, then the root'],
  ['find', 'Find a unit'],
  ['step', 'Step through keypairs'],
  ['act', 'Follow a keypair, or make the root'],
  ['root', 'Make the root'],
] as const;
export type KeyAction = (typeof KEY_ACTIONS)[number][0];

const vector = (v: unknown) => Array.isArray(v) && v.length === 3 && v.every((x) => typeof x === 'number');
const reaches = (v: unknown) =>
  Array.isArray(v) && v.length >= 1 && v.every((x) => typeof x === 'number' && x >= 0 && x <= 200);

