// Starting view, reading the data (6.6) and the layout (6.1). These take effect with the next graph.
import type { Key } from '../../core/index.ts';
import { DATE_PATTERN, EXTENT, STEP, TIME_NAMES, TYPE_NAMES } from '../defaults.ts';
import {
  CheckboxSetting,
  JsonSetting,
  NumberSetting,
  SelectSetting,
  SetSetting,
  SliderSetting,
  TextSetting,
} from '../setting.svelte.ts';

const names = (v: unknown) => Array.isArray(v) && v.every((x) => typeof x === 'string' && x.length > 0);
const keys = (v: unknown) =>
  Array.isArray(v) && v.every((x) => typeof x === 'string' || (typeof x === 'number' && Number.isSafeInteger(x)));

export const viewSettings = () =>
  [
    new SelectSetting({
      key: 'view.mode',
      group: 'Starting view',
      label: 'Starting mode',
      description: 'The view a viewer starts in; a graph’s own view may choose another.',
      default: '2d',
      options: [
        ['2d', '2D'],
        ['3d', '3D'],
      ],
      applies: 'load',
    }),
    new SetSetting({
      key: 'view.keep',
      group: 'Starting view',
      label: 'Kept for the next graph',
      description: 'What a new graph takes over from the last one. Root, path and inspection always start afresh.',
      default: ['mode', 'hulls'],
      items: [
        ['mode', '2D or 3D'],
        ['hulls', 'Hulls'],
        ['types', 'Type names and colours'],
        ['filters', 'Filters'],
      ],
      applies: 'load',
    }),
  ] as const;

